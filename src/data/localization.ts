export function getLokiComment(trigger: LokiCommentTrigger, seedIndex: number): string {
  const pool = LOKI_REACTIVE_COMMENTS[trigger];
  if (!pool || pool.length === 0) {
    return 'KEEP MOVING, MORTAL!';
  }
  const idx = Math.abs(Math.floor(seedIndex)) % pool.length;
  return pool[idx];
}
